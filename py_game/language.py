LANGUAGE_TYPES = {
    EnglishLanguage.code: EnglishLanguage,
    CzechLanguage.code: CzechLanguage,
}
LANGUAGE_CODES = tuple(LANGUAGE_TYPES)


def get_language(code: str) -> EnglishLanguage:
    return LANGUAGE_TYPES.get(code, EnglishLanguage)()


def next_language_code(code: str, direction: int = 1) -> str:
    try:
        index = LANGUAGE_CODES.index(code)
    except ValueError:
        index = 0
    return LANGUAGE_CODES[(index + direction) % len(LANGUAGE_CODES)]
