from __future__ import annotations


class Language:
    """Base interface for user-facing text.

    Translation keys are ordinary class attributes on purpose: adding a new
    language is as small as inheriting EnglishLanguage and overriding fields.
    """

    code = "en"
    name = "English"

    def text(self, key: str, **values) -> str:
        value = getattr(self, key, key.replace("_", " ").title())
        return value.format(**values) if values else value


